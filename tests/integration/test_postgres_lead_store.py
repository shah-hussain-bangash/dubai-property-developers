"""Live PostgreSQL integration tests for PostgresLeadStore.

Run only when RUN_INTEGRATION_TESTS=1.

Requirements:
- Development PostgreSQL database is running.
- Alembic migrations through 0003 are applied.
- Organizations demo-org and tenant-isolation-test exist.
- demo-org contains at least one fictional template lead.

All newly created test leads are removed after each test.
"""

from __future__ import annotations

import asyncio
import uuid
from collections.abc import AsyncIterator
from dataclasses import dataclass, field

import pytest
from sqlalchemy import delete, func, select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from core.config.settings import get_settings
from database.models.crm import Lead
from database.models.identity import Organization
from database.repositories.postgres_lead_store import (
    PostgresLeadStore,
    lead_dedupe_keys,
)
from database.sessions.engine import (
    create_engine,
    create_session_factory,
)
from schemas.leads.models import NormalizedLead
from tests.factories import integration_enabled

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(
        not integration_enabled(),
        reason="Set RUN_INTEGRATION_TESTS=1",
    ),
]

ORG_A = "demo-org"
ORG_B = "tenant-isolation-test"


@dataclass
class LeadTestContext:
    store: PostgresLeadStore
    factory: async_sessionmaker[AsyncSession]
    template: NormalizedLead
    created_ids: list[uuid.UUID] = field(default_factory=list)

    def new_lead(
        self,
        name: str,
        tenant_id: str = ORG_A,
        keys: list[str] | None = None,
    ) -> NormalizedLead:
        """Create a fictional lead based on a valid example."""

        new_id = uuid.uuid4()
        self.created_ids.append(new_id)

        lead = self.template.model_copy(deep=True)

        lead.lead_id = str(new_id)
        lead.tenant_id = tenant_id
        lead.full_name = name

        lead.email = f"test-{new_id.hex}@example.com"
        lead.phone_e164 = None
        lead.phone_region = None

        lead.external_ref = None
        lead.message = "Automated PostgreSQL test lead"

        lead.consent_marketing = False
        lead.consent_whatsapp = False

        lead.dedupe_keys = keys if keys is not None else [f"test:automated:{new_id.hex}"]

        return lead


@pytest.fixture
async def lead_context() -> AsyncIterator[LeadTestContext]:
    """Provide a database-backed store with safe test cleanup."""

    settings = get_settings()

    if not settings.is_dev_like:
        pytest.skip("Live LeadStore tests require a development database")

    engine = create_engine(settings)
    factory = create_session_factory(engine)
    store = PostgresLeadStore(factory)

    ctx: LeadTestContext | None = None

    try:
        async with factory() as session:
            organizations = await session.scalars(
                select(Organization.slug).where(
                    Organization.slug.in_([ORG_A, ORG_B]),
                    Organization.is_active.is_(True),
                )
            )

            found = set(organizations.all())

        if found != {ORG_A, ORG_B}:
            pytest.skip("Required fictional test organizations are missing")

        existing = await store.list(ORG_A)

        if not existing:
            pytest.skip("A fictional template lead is required in demo-org")

        ctx = LeadTestContext(
            store=store,
            factory=factory,
            template=existing[0],
        )

        yield ctx

    finally:
        try:
            if ctx is not None and ctx.created_ids:
                async with factory() as session, session.begin():
                    # Only delete lead IDs generated by these tests.
                    await session.execute(
                        delete(lead_dedupe_keys).where(
                            lead_dedupe_keys.c.lead_id.in_(ctx.created_ids)
                        )
                    )

                    await session.execute(delete(Lead).where(Lead.id.in_(ctx.created_ids)))
        finally:
            await engine.dispose()


async def test_create_and_retrieve_lead(
    lead_context: LeadTestContext,
) -> None:
    ctx = lead_context

    lead = ctx.new_lead("Automated Creation Test")

    await ctx.store.save(lead)

    found = await ctx.store.find_by_dedupe_keys(
        ORG_A,
        lead.dedupe_keys,
    )

    assert len(found) == 1
    assert found[0].lead_id == lead.lead_id
    assert found[0].full_name == lead.full_name

    all_leads = await ctx.store.list(ORG_A)

    assert any(item.lead_id == lead.lead_id for item in all_leads)


async def test_update_and_consent_preservation(
    lead_context: LeadTestContext,
) -> None:
    ctx = lead_context

    lead = ctx.new_lead("Automated Update Test")

    await ctx.store.save(lead)

    lead.full_name = "Updated Automated Lead"
    lead.message = "Updated by automated test"

    lead.consent_marketing = True
    lead.consent_whatsapp = False

    await ctx.store.save(lead)

    matches = await ctx.store.find_by_dedupe_keys(
        ORG_A,
        lead.dedupe_keys,
    )

    assert len(matches) == 1

    stored = matches[0]

    assert stored.lead_id == lead.lead_id
    assert stored.full_name == "Updated Automated Lead"
    assert stored.message == "Updated by automated test"

    assert stored.consent_marketing is True
    assert stored.consent_whatsapp is False


async def test_multiple_duplicate_keys(
    lead_context: LeadTestContext,
) -> None:
    ctx = lead_context

    token = uuid.uuid4().hex

    email_key = f"email:test-{token}@example.com"
    phone_key = f"phone:test-{token}"

    lead = ctx.new_lead(
        "Multiple Keys Test",
        keys=[email_key, phone_key],
    )

    await ctx.store.save(lead)

    email_matches = await ctx.store.find_by_dedupe_keys(
        ORG_A,
        [email_key],
    )

    phone_matches = await ctx.store.find_by_dedupe_keys(
        ORG_A,
        [phone_key],
    )

    assert len(email_matches) == 1
    assert len(phone_matches) == 1

    assert email_matches[0].lead_id == lead.lead_id
    assert phone_matches[0].lead_id == lead.lead_id

    assert set(email_matches[0].dedupe_keys) == {
        email_key,
        phone_key,
    }


async def test_sequential_duplicate_is_rejected(
    lead_context: LeadTestContext,
) -> None:
    ctx = lead_context

    shared_key = "test:sequential:" + uuid.uuid4().hex

    lead_a = ctx.new_lead(
        "Sequential Lead A",
        keys=[shared_key],
    )

    lead_b = ctx.new_lead(
        "Sequential Lead B",
        keys=[shared_key],
    )

    await ctx.store.save(lead_a)

    with pytest.raises(
        ValueError,
        match="deduplication keys",
    ):
        await ctx.store.save(lead_b)

    matches = await ctx.store.find_by_dedupe_keys(
        ORG_A,
        [shared_key],
    )

    assert len(matches) == 1
    assert matches[0].lead_id == lead_a.lead_id

    async with ctx.factory() as session:
        failed_lead = await session.get(
            Lead,
            uuid.UUID(lead_b.lead_id),
        )

    assert failed_lead is None


async def test_tenant_isolation(
    lead_context: LeadTestContext,
) -> None:
    ctx = lead_context

    shared_key = "test:tenant:" + uuid.uuid4().hex

    lead_a = ctx.new_lead(
        "Organization A Lead",
        tenant_id=ORG_A,
        keys=[shared_key],
    )

    lead_b = ctx.new_lead(
        "Organization B Lead",
        tenant_id=ORG_B,
        keys=[shared_key],
    )

    # Identical keys are allowed across organizations.
    await ctx.store.save(lead_a)
    await ctx.store.save(lead_b)

    matches_a = await ctx.store.find_by_dedupe_keys(
        ORG_A,
        [shared_key],
    )

    matches_b = await ctx.store.find_by_dedupe_keys(
        ORG_B,
        [shared_key],
    )

    assert len(matches_a) == 1
    assert len(matches_b) == 1

    assert matches_a[0].lead_id == lead_a.lead_id
    assert matches_b[0].lead_id == lead_b.lead_id

    org_a_leads = await ctx.store.list(ORG_A)
    org_b_leads = await ctx.store.list(ORG_B)

    assert all(item.lead_id != lead_b.lead_id for item in org_a_leads)

    assert all(item.lead_id != lead_a.lead_id for item in org_b_leads)


async def test_cross_tenant_overwrite_blocked(
    lead_context: LeadTestContext,
) -> None:
    ctx = lead_context

    original = ctx.new_lead(
        "Protected Organization A Lead",
        tenant_id=ORG_A,
    )

    await ctx.store.save(original)

    unauthorized = original.model_copy(deep=True)

    unauthorized.tenant_id = ORG_B
    unauthorized.full_name = "Unauthorized Change"

    with pytest.raises(
        ValueError,
        match="another organization",
    ):
        await ctx.store.save(unauthorized)

    matches = await ctx.store.find_by_dedupe_keys(
        ORG_A,
        original.dedupe_keys,
    )

    assert len(matches) == 1
    assert matches[0].full_name == original.full_name


async def test_concurrent_duplicate_and_rollback(
    lead_context: LeadTestContext,
) -> None:
    ctx = lead_context

    shared_key = "test:concurrent:" + uuid.uuid4().hex

    lead_a = ctx.new_lead(
        "Concurrent Lead A",
        keys=[shared_key],
    )

    lead_b = ctx.new_lead(
        "Concurrent Lead B",
        keys=[shared_key],
    )

    results = await asyncio.gather(
        ctx.store.save(lead_a),
        ctx.store.save(lead_b),
        return_exceptions=True,
    )

    successful = sum(result is None for result in results)

    failures = [result for result in results if isinstance(result, Exception)]

    assert successful == 1
    assert len(failures) == 1

    assert isinstance(failures[0], ValueError)
    assert "deduplication keys" in str(failures[0])

    async with ctx.factory() as session:
        org_id = await session.scalar(select(Organization.id).where(Organization.slug == ORG_A))

        key_count = await session.scalar(
            select(func.count())
            .select_from(lead_dedupe_keys)
            .where(
                lead_dedupe_keys.c.organization_id == org_id,
                lead_dedupe_keys.c.dedupe_key == shared_key,
            )
        )

        lead_count = await session.scalar(
            select(func.count())
            .select_from(Lead)
            .where(
                Lead.id.in_(
                    [
                        uuid.UUID(lead_a.lead_id),
                        uuid.UUID(lead_b.lead_id),
                    ]
                )
            )
        )

    assert key_count == 1
    assert lead_count == 1
