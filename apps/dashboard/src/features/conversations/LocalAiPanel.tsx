'use client';
import { useEffect, useRef, useState, type FormEvent } from 'react';
import { generateLocalDraft, type LocalDraft } from '@/services/localAi';
import styles from './LocalAiPanel.module.css';
export function LocalAiPanel() {
  const [message, setMessage] = useState('A fictional buyer wants a two-bedroom apartment. Ask three questions to clarify their requirements.');
  const [result, setResult] = useState<LocalDraft | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const active = useRef<AbortController | null>(null);
  const mounted = useRef(true);
  useEffect(() => { mounted.current = true; return () => { mounted.current = false; active.current?.abort(); }; }, []);
  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault(); if (active.current) return;
    const controller = new AbortController(); active.current = controller;
    setBusy(true); setResult(null); setError('');
    const timer = setTimeout(() => controller.abort(), 130000);
    try { const value = await generateLocalDraft(message, controller.signal); if (mounted.current && !controller.signal.aborted) setResult(value); }
    catch { if (mounted.current) setError('Local AI could not finish. Keep Ollama running, wait for any current reply to finish, then try again manually.'); }
    finally { clearTimeout(timer); active.current = null; if (mounted.current) setBusy(false); }
  }
  return <section className={'panel ' + styles.panel} aria-labelledby="local-ai-title">
    <div className="panel-header"><h2 className="panel-title" id="local-ai-title">Try real local AI</h2><span>Qwen3 8B · on your PC</span></div>
    <p>This panel generates a real AI reply using Ollama on your computer. No paid API is used. Use fictional enquiries only. Replies are unverified drafts and may contain mistakes; a person must review them. Nothing is sent to a customer.</p>
    <form onSubmit={submit}>
      <label htmlFor="local-ai-message">Fictional enquiry for local AI</label>
      <textarea id="local-ai-message" required minLength={3} maxLength={1000} rows={3} disabled={busy} value={message} onChange={event => { setMessage(event.target.value); setResult(null); setError(''); }} />
      <div className={styles.actions}><button className="btn btn-primary" disabled={busy} type="submit">{busy ? 'Generating on your PC…' : 'Generate local AI draft'}</button><button className="btn" disabled={busy} type="button" onClick={() => { setMessage(''); setResult(null); setError(''); }}>Clear local AI draft</button></div>
    </form>
    {busy && <p role="status">Your local model is generating. The first reply may take up to two minutes.</p>}
    {error && <p role="alert">{error}</p>}
    {result && <div className={styles.result} aria-live="polite"><h3>Local AI draft · review required</h3><blockquote dir="auto">{result.text}</blockquote><p>Generated by local qwen3:8b · {result.input_tokens} input / {result.output_tokens} output tokens · Unsent</p></div>}
  </section>;
}
