'use client';
import { useEffect, useRef, useState, type FormEvent } from 'react';
import { askLocalKnowledge, type LocalKnowledge } from '@/services/localKnowledge';
import styles from '@/features/conversations/LocalAiPanel.module.css';
export function LocalKnowledgePanel() {
  const [question,setQuestion]=useState('What is the payment plan for Demo Creek Heights?');
  const [result,setResult]=useState<LocalKnowledge|null>(null);
  const [busy,setBusy]=useState(false); const [error,setError]=useState('');
  const active=useRef<AbortController|null>(null); const mounted=useRef(true);
  useEffect(()=>{mounted.current=true;return()=>{mounted.current=false;active.current?.abort();};},[]);
  function change(text:string) {setQuestion(text);setResult(null);setError('');}
  async function submit(event:FormEvent<HTMLFormElement>) {
    event.preventDefault();if(active.current)return;
    const controller=new AbortController();active.current=controller;setBusy(true);setResult(null);setError('');
    const timer=setTimeout(()=>controller.abort(),130000);
    try{const value=await askLocalKnowledge(question,controller.signal);if(mounted.current&&!controller.signal.aborted)setResult(value);}
    catch{if(mounted.current)setError('Local knowledge drafting could not finish. Keep Ollama running, wait for any active reply, then try again manually.');}
    finally{clearTimeout(timer);active.current=null;if(mounted.current)setBusy(false);}
  }
  return <section className={'panel '+styles.panel} aria-labelledby="local-knowledge-title">
    <div className="panel-header"><h2 className="panel-title" id="local-knowledge-title">Ask local AI from fictional sources</h2><span>Qwen3 8B · source-assisted draft</span></div>
    <p>Qwen drafts an answer using retrieved public fictional passages. Source labels show the passages supplied to the model; they do not verify every generated claim. Review the answer and confirm terms before use. No paid API or customer delivery is used.</p>
    <form onSubmit={submit}><label htmlFor="local-knowledge-question">Fictional question for source-assisted AI</label>
      <textarea id="local-knowledge-question" required rows={3} minLength={3} maxLength={1000} disabled={busy} value={question} onChange={event=>change(event.target.value)} />
      <div className={styles.actions}><button className="btn btn-primary" type="submit" disabled={busy}>{busy?'Drafting from fictional sources…':'Ask local AI with sources'}</button><button className="btn" type="button" disabled={busy} onClick={()=>change('')}>Clear source-assisted draft</button></div>
    </form>
    {busy&&<p role="status">Retrieving public fictional passages and generating locally. This may take up to two minutes.</p>}
    {error&&<p role="alert">{error}</p>}
    {result&&!result.generated&&<div role="status"><h3>Staff confirmation needed</h3><p>{result.reason}</p><p>No AI answer was generated. Nothing was sent.</p></div>}
    {result&&result.generated&&<div className={styles.result} aria-live="polite"><h3>Local knowledge draft · review required</h3><blockquote dir="auto">{result.text}</blockquote>
      <h4>Sources supplied to Qwen</h4>{result.sources.map(source=><article key={source.label}><h5>[{source.label}] {source.title} · Version {source.version}</h5><blockquote>{source.excerpt}</blockquote></article>)}
      <p>{result.confirmation}</p><p>Generated by local qwen3:8b · Unsent · Human review required</p>
    </div>}
  </section>;
}
